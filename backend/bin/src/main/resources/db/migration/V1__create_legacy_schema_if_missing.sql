-- Empty installations need the Phase 1/2 tables before the preserving
-- backfill can run. Existing installations are baselined at this version.
CREATE TABLE IF NOT EXISTS account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    cash_balance NUMERIC(19,2)
);

CREATE TABLE IF NOT EXISTS stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(255) NOT NULL,
    company_name VARCHAR(255),
    current_price NUMERIC(19,2),
    CONSTRAINT uk_stock_symbol UNIQUE (symbol)
);

CREATE TABLE IF NOT EXISTS portfolio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT,
    stock_id BIGINT,
    quantity INTEGER,
    CONSTRAINT fk_portfolio_account FOREIGN KEY (account_id) REFERENCES account(id),
    CONSTRAINT fk_portfolio_stock FOREIGN KEY (stock_id) REFERENCES stock(id)
);

CREATE TABLE IF NOT EXISTS transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT,
    stock_id BIGINT,
    type VARCHAR(255),
    quantity INTEGER,
    price NUMERIC(19,2),
    trade_value NUMERIC(19,2),
    brokerage NUMERIC(19,2),
    total_amount NUMERIC(19,2),
    transaction_time TIMESTAMP,
    CONSTRAINT fk_transaction_account FOREIGN KEY (account_id) REFERENCES account(id),
    CONSTRAINT fk_transaction_stock FOREIGN KEY (stock_id) REFERENCES stock(id)
);
