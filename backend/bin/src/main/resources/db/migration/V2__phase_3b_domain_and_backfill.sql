-- Phase 3B is additive. No legacy row is deleted or rewritten.
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254),
    password_hash VARCHAR(255),
    display_name VARCHAR(120),
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_user_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS trading_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    cash NUMERIC(20,2) NOT NULL,
    realized_pnl NUMERIC(20,2) NOT NULL DEFAULT 0,
    charges NUMERIC(20,2) NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_trading_account_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS securities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_stock_id BIGINT UNIQUE,
    symbol VARCHAR(255) NOT NULL UNIQUE,
    company_name VARCHAR(255),
    current_price NUMERIC(19,2),
    CONSTRAINT fk_security_legacy_stock FOREIGN KEY (legacy_stock_id) REFERENCES stock(id)
);

CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    security_id BIGINT NOT NULL,
    side VARCHAR(20) NOT NULL,
    type VARCHAR(20) NOT NULL,
    status VARCHAR(25) NOT NULL,
    quantity INTEGER NOT NULL,
    requested_price NUMERIC(24,6),
    executed_price NUMERIC(24,6),
    charges NUMERIC(20,2) NOT NULL DEFAULT 0,
    rejection_reason VARCHAR(500),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    executed_at TIMESTAMP,
    CONSTRAINT fk_order_account FOREIGN KEY (account_id) REFERENCES trading_accounts(id),
    CONSTRAINT fk_order_security FOREIGN KEY (security_id) REFERENCES securities(id)
);

CREATE TABLE IF NOT EXISTS positions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    security_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    average_cost NUMERIC(24,6) NOT NULL DEFAULT 0,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_position_account_security UNIQUE (account_id, security_id),
    CONSTRAINT fk_position_account FOREIGN KEY (account_id) REFERENCES trading_accounts(id),
    CONSTRAINT fk_position_security FOREIGN KEY (security_id) REFERENCES securities(id)
);

CREATE TABLE IF NOT EXISTS trade_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    security_id BIGINT NOT NULL,
    side VARCHAR(20) NOT NULL,
    entry_price NUMERIC(24,6) NOT NULL,
    stop_price NUMERIC(24,6) NOT NULL,
    target_price NUMERIC(24,6) NOT NULL,
    quantity INTEGER NOT NULL,
    thesis VARCHAR(2000),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT fk_plan_account FOREIGN KEY (account_id) REFERENCES trading_accounts(id),
    CONSTRAINT fk_plan_security FOREIGN KEY (security_id) REFERENCES securities(id)
);

CREATE TABLE IF NOT EXISTS journal_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    order_id BIGINT,
    trade_id BIGINT,
    thesis VARCHAR(2000), reason VARCHAR(2000),
    emotional_state VARCHAR(40), confidence NUMERIC(19,6),
    strategy VARCHAR(40), notes VARCHAR(5000), outcome VARCHAR(1000),
    lessons VARCHAR(2000), mistake_category VARCHAR(40),
    created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP,
    CONSTRAINT fk_journal_account FOREIGN KEY (account_id) REFERENCES trading_accounts(id),
    CONSTRAINT fk_journal_order FOREIGN KEY (order_id) REFERENCES orders(id),
    CONSTRAINT fk_journal_trade FOREIGN KEY (trade_id) REFERENCES transactions(id)
);

CREATE TABLE IF NOT EXISTS alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    type VARCHAR(40) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP,
    CONSTRAINT fk_alert_account FOREIGN KEY (account_id) REFERENCES trading_accounts(id)
);

CREATE TABLE IF NOT EXISTS portfolio_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    portfolio_value NUMERIC(20,2) NOT NULL, cash NUMERIC(20,2) NOT NULL,
    invested NUMERIC(20,2) NOT NULL, realized_pnl NUMERIC(20,2) NOT NULL,
    unrealized_pnl NUMERIC(20,2) NOT NULL, drawdown NUMERIC(20,2) NOT NULL,
    captured_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_snapshot_account FOREIGN KEY (account_id) REFERENCES trading_accounts(id)
);

-- Extensions are nullable because old transactions do not have an order.
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS trading_account_id BIGINT;
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS order_id BIGINT;
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS realized_pnl NUMERIC(20,2);

-- Deterministic identities are explicitly marked as legacy and have no usable
-- password. They can be replaced by an application registration flow later.
INSERT INTO users (email, password_hash, display_name, created_at, updated_at)
SELECT 'legacy-account-' || CAST(a.id AS VARCHAR(30)) || '@invalid.local',
       'LEGACY_NO_PASSWORD', COALESCE(a.name, 'Legacy account'),
       CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM account a
WHERE NOT EXISTS (
    SELECT 1 FROM users u
    WHERE u.email = 'legacy-account-' || CAST(a.id AS VARCHAR(30)) || '@invalid.local'
);

INSERT INTO trading_accounts (user_id, cash, realized_pnl, charges, created_at, updated_at)
SELECT u.id, COALESCE(a.cash_balance, 0), 0, 0, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM account a
JOIN users u ON u.email = 'legacy-account-' || CAST(a.id AS VARCHAR(30)) || '@invalid.local'
WHERE NOT EXISTS (SELECT 1 FROM trading_accounts ta WHERE ta.user_id = u.id);

INSERT INTO securities (legacy_stock_id, symbol, company_name, current_price)
SELECT s.id, s.symbol, s.company_name, s.current_price
FROM stock s
WHERE NOT EXISTS (SELECT 1 FROM securities x WHERE x.legacy_stock_id = s.id);

INSERT INTO positions (account_id, security_id, quantity, average_cost, updated_at)
SELECT ta.id, sec.id, p.quantity, COALESCE(sec.current_price, 0), CURRENT_TIMESTAMP
FROM portfolio p
JOIN trading_accounts ta ON ta.user_id = (
    SELECT u.id FROM users u JOIN account a ON u.email =
        'legacy-account-' || CAST(a.id AS VARCHAR(30)) || '@invalid.local'
    WHERE a.id = p.account_id
)
JOIN securities sec ON sec.legacy_stock_id = p.stock_id
WHERE p.quantity IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM positions x
    WHERE x.account_id = ta.id AND x.security_id = sec.id
);

UPDATE transactions t
SET trading_account_id = (
    SELECT ta.id
    FROM account a
    JOIN users u ON u.email = 'legacy-account-' || CAST(a.id AS VARCHAR(30)) || '@invalid.local'
    JOIN trading_accounts ta ON ta.user_id = u.id
    WHERE a.id = t.account_id
)
WHERE t.trading_account_id IS NULL;
