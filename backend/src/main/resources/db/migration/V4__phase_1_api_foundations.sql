CREATE UNIQUE INDEX IF NOT EXISTS idx_securities_symbol_unique
    ON securities (symbol);

ALTER TABLE trading_accounts
    ADD CONSTRAINT chk_trading_accounts_cash_nonnegative CHECK (cash >= 0);

ALTER TABLE positions
    ADD CONSTRAINT chk_positions_quantity_nonnegative CHECK (quantity >= 0);

CREATE TABLE watchlist_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    security_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_watchlist_account_security UNIQUE (account_id, security_id),
    CONSTRAINT fk_watchlist_account FOREIGN KEY (account_id) REFERENCES trading_accounts(id),
    CONSTRAINT fk_watchlist_security FOREIGN KEY (security_id) REFERENCES securities(id)
);
